def validate(cases):
    errors = []
    for idx, c in enumerate(cases, 1):
        rid = c.get("需求ID")
        if rid not in REQ_TITLES:
            errors.append(f"第{idx}条用例需求ID未登记: {rid}")
        if c.get("优先级") not in ("P0", "P1", "P2", "P3"):
            errors.append(f"第{idx}条用例优先级非法: {c.get('优先级')}")
        methods = c.get("设计方法") or []
        if not methods or not set(methods) <= {"EP", "BVA", "ST", "EG"}:
            errors.append(f"第{idx}条用例设计方法非法: {methods}")
        steps = c.get("步骤") or []
        if not steps:
            errors.append(f"第{idx}条用例无步骤: {c.get('用例标题')}")
        for s in steps:
            if not s.get("操作") or not s.get("预期"):
                errors.append(f"第{idx}条用例步骤缺少操作或预期")
    return errors


def stats(cases):
    covered = sorted({c["需求ID"] for c in cases})
    uncovered = [r for r in REQ_TITLES if r not in covered]
    coverage = len(covered) / len(REQ_TITLES) * 100
    pri = {"P0": 0, "P1": 0, "P2": 0, "P3": 0}
    methods = {"EP": 0, "BVA": 0, "ST": 0, "EG": 0}
    for c in cases:
        pri[c["优先级"]] += 1
        for m in c["设计方法"]:
            methods[m] += 1
    return covered, uncovered, coverage, pri, methods


